CREATE POLICY "Authenticated users can insert bill_items"
ON public.bill_items FOR INSERT WITH CHECK (auth.uid() IS NOT NULL);

/* -----------------------------------------------------------------------------
   BILL NUMBER GENERATION — DUPLICATE PREVENTION & PRODUCTION NOTES

   How duplicates are prevented:
   1. pg_advisory_xact_lock(v_lock_key) — all inserts for the same calendar day
      take the same lock (key = YYYYMMDD as integer). Only one insert at a time
      for that day can run the COUNT + assign sequence, so each gets a unique
      sequence (count+1). The lock is transaction-scoped and released at commit.
   2. UNIQUE (bill_number) on bills — database enforces uniqueness; any
      duplicate would raise a constraint violation.

   Production suggestions:
   - idx_bills_created_at on created_at helps range queries; the trigger's
     COUNT uses created_at::date = CURRENT_DATE (expression index on that
     cast is not allowed — cast depends on session timezone, not immutable).
   - For very high throughput (many bills per second), the per-day advisory lock
     serializes inserts for that day; consider connection pooling and short
     transactions to avoid long waits.
   - If you need bill numbers by timezone (e.g. store local date), use a
     session variable or pass the date; CURRENT_DATE uses the database
     timezone (typically UTC in Supabase).
   ----------------------------------------------------------------------------- */
